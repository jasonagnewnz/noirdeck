"""Zero-egress mining: skill-gap candidates, memory groupings, builder profile."""

from __future__ import annotations

import re
import sqlite3
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from ..config import primary_namespace
from ..db import utcnow
from ..readers import history as hist
from ..readers.memories import group_memories, list_memories
from ..readers.skills import list_skills

NZ = ZoneInfo("Pacific/Auckland")


def _skill_vocab(skills: list[dict]) -> set[str]:
    vocab: set[str] = set()
    for s in skills:
        vocab.update(re.split(r"[^a-z0-9]+", s["name"].lower()))
        vocab.update(w for w in re.split(r"[^a-z0-9]+", s["description"].lower()[:200]) if len(w) > 4)
    vocab.discard("")
    return vocab


def skill_candidates(records: list[dict], skills: list[dict], min_count: int = 3) -> list[dict]:
    """Repeated prompts whose key terms don't appear in any existing skill."""
    vocab = _skill_vocab(skills)
    out = []
    for rp in hist.repeated_prompts(records, min_count=min_count):
        words = [w for w in rp["normalized"].split() if len(w) > 4]
        if not words:
            continue
        novel = [w for w in words if w not in vocab]
        # mostly-covered prompts are already served by a skill; want mostly-novel
        if len(novel) >= max(1, len(words) // 2):
            slug = "-".join(words[:4])[:48]
            out.append({**rp, "suggested_slug": slug, "novel_terms": novel[:8]})
    return out[:25]


def draft_skill_body(candidate: dict) -> str:
    return f"""---
name: {candidate["suggested_slug"]}
description: DRAFT (noirdeck) — captures a prompt you have typed {candidate["count"]}x: "{candidate["example"][:140]}". Refine the trigger description, add the concrete steps/landmines, then keep or discard.
---

# /{candidate["suggested_slug"]} — DRAFT

You asked for this (or nearly this) {candidate["count"]} times, in: {", ".join(candidate["projects"][:5])}.

Latest example:
> {candidate["example"]}

## TODO before this is a real skill
- Write the actual procedure the sessions converged on (check the transcripts of the
  projects above for what worked).
- Add the landmines hit along the way.
- Tighten the description into a trigger ("Use when ...").
"""


def build_profile(records: list[dict], claude_dir: Path) -> str:
    stats = hist.history_stats(records)
    skills = list_skills(claude_dir)
    mems = list_memories(claude_dir)
    hours = stats["by_hour"]
    peak = sorted(range(24), key=lambda h: -hours[h])[:3]
    top_proj = "\n".join(f"- {p} — {c} prompts" for p, c in stats["top_projects"][:8])
    top_slash = ", ".join(f"{s} ({c})" for s, c in stats["top_slash"][:8])
    return f"""---
name: builder-profile-noirdeck
description: Generated builder profile — how you actually work, from {stats["total_prompts"]} prompts of real history. Regenerated by noirdeck; edits belong in the generator or a separate curated file.
metadata:
  type: user
---

# Builder profile (generated {datetime.now(NZ).strftime("%Y-%m-%d")})

- **Volume**: {stats["total_prompts"]} prompts on record; average non-slash prompt {stats["avg_prompt_chars"]} chars.
- **Peak working hours (NZ)**: {", ".join(f"{h:02d}:00" for h in sorted(peak))}.
- **Estate**: {len(skills)} skills, {len(mems)} memory files across the namespaces.
- **Most-used slash commands**: {top_slash or "n/a"}.

## Where the time goes
{top_proj}

## Delivery methodology (observed)
1. Orient from memory/skills before acting (/operate, /context-prime discipline).
2. Verify against live state, not notes; empty results are checked for dead sensors.
3. Propose-only on anything outward-facing or destructive; explicit ID selection.
4. Ship = deployed + verified on the running artifact, never just green CI.
5. Record landmines as memories/skills so the next session inherits them.
"""


def run_heuristics(conn: sqlite3.Connection, claude_dir: Path) -> dict:
    """Compute candidates + groupings + profile; stage as proposals (dedup by title)."""
    records = hist.load_history(claude_dir)
    skills = list_skills(claude_dir)
    created = 0

    def propose(kind: str, title: str, body: str, target_path: str | None) -> None:
        nonlocal created
        dup = conn.execute("SELECT 1 FROM proposals WHERE title=? AND status='proposed'", (title,)).fetchone()
        if dup:
            return
        conn.execute(
            "INSERT INTO proposals (kind,title,body,target_path,status,created_at) VALUES (?,?,?,?,'proposed',?)",
            (kind, title, body, target_path, utcnow()),
        )
        created += 1

    cands = skill_candidates(records, skills)
    for c in cands[:10]:
        propose(
            "skill",
            f"Draft skill: /{c['suggested_slug']} (asked {c['count']}x)",
            draft_skill_body(c),
            f"skills/{c['suggested_slug']}/SKILL.md",
        )

    mems = list_memories(claude_dir)
    for g in group_memories(mems)[:8]:
        title = f"Memory consolidation: '{g['topic']}' x{g['count']} in {g['namespace']}"
        body = (
            f"{g['count']} memory files in `{g['namespace']}` share the topic '{g['topic']}'.\n"
            "Candidate consolidation into one topic file with the members as sections:\n\n"
            + "\n".join(f"- [[{m}]]" for m in g["members"])
            + "\n\nApprove writes a stub topic file; merging content stays a human/Claude session task."
        )
        propose("memory_group", title, body, None)

    propose(
        "profile_doc",
        "Builder profile & delivery methodology (regenerate)",
        build_profile(records, claude_dir),
        f"projects/{primary_namespace()}/memory/builder-profile-noirdeck.md",
    )
    conn.commit()
    return {"proposals_created": created, "skill_candidates": len(cands)}
