"""Zero-egress mining: the builder profile, computed from history statistics.

WHAT WAS REMOVED HERE, AND WHY IT MUST NOT COME BACK (2026-08-19)
This module used to generate two kinds of proposal from string matching, and both
were wrong in a way that reached every session on the estate:

1. `skill_candidates()` called a repeated prompt a "skill gap" when at least half
   its >4-character words did not appear in existing skill names/descriptions.
   Vocabulary overlap is not evidence that a procedure exists. It wrote ten draft
   skills into ~/.claude/skills/, among them a pasted Windows path
   (`mntcusersjdoeexamplecorpbinchitexe-force`), a username (`ddonald01`),
   and `commit-please`. Every one of those then loaded into every session.

2. Memory consolidation grouped files that shared ONE filename token longer than
   two characters and absent from a 22-word stopword list. Against the real
   estate (18,062 memory files) that produced 96 "consolidation candidates",
   topped by `topic='2026'` with 166 members: i.e. every date-suffixed file in
   the namespace: and `topic='wazuh'` with 35 distinct incidents on distinct
   dates. Sharing a word is not sharing a topic.

The operator's rule (2026-08-19): a proposal may exist only when a model has
actually READ the candidate material and can state the specific repeated
procedure or the specific redundancy, citing its source. Proposals are now
generated exclusively in miner/runner.py, from that evidence, and validated by
miner/evidence.py. Do not reintroduce a token-, vocabulary- or filename-based
generator here; the profile below is statistical, describes only noirdeck's own
generated file, and asserts nothing about the operator's files.
"""

from __future__ import annotations

import sqlite3
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from ..config import primary_namespace
from ..db import utcnow
from ..readers import history as hist
from ..readers.memories import list_memories
from ..readers.skills import list_skills

NZ = ZoneInfo("Pacific/Auckland")


def build_profile(records: list[dict], claude_dir: Path) -> str:
    stats = hist.history_stats(records)
    skills = list_skills(claude_dir)
    mems = list_memories(claude_dir)
    hours = stats["by_hour"]
    peak = sorted(range(24), key=lambda h: -hours[h])[:3]
    top_proj = "\n".join(f"- {p}: {c} prompts" for p, c in stats["top_projects"][:8])
    top_slash = ", ".join(f"{s} ({c})" for s, c in stats["top_slash"][:8])
    return f"""---
name: builder-profile-noirdeck
description: Generated builder profile: how you actually work, from {stats["total_prompts"]} prompts of real history. Regenerated by noirdeck as a new dated file each time; edits belong in the generator or a separate curated file.
metadata:
  type: user
---

# Builder profile (generated {datetime.now(NZ).strftime("%Y-%m-%d")})

- **Volume**: {stats["total_prompts"]} prompts on record; average non-slash prompt {stats["avg_prompt_chars"]} chars.
- **Peak working hours (NZ)**: {", ".join(f"{h:02d}:00" for h in sorted(peak))}.
- **Estate**: {len(skills)} skills, {len(mems)} memory files across the namespaces.
- **Most-used slash commands**: {top_slash or "n/a"}.

## Where the time goes
{top_proj}

## Delivery methodology (observed)
1. Orient from memory/skills before acting (/operate, /context-prime discipline).
2. Verify against live state, not notes; empty results are checked for dead sensors.
3. Propose-only on anything outward-facing or destructive; explicit ID selection.
4. Ship = deployed + verified on the running artifact, never just green CI.
5. Record landmines as memories/skills so the next session inherits them.
"""


def profile_target_path() -> str:
    """A new dated file per regeneration. Approval is create-only, so a fixed
    name could be written exactly once and every later regeneration would be
    unappliable; dating it keeps the feature working without ever replacing the
    previous profile."""
    day = datetime.now(NZ).strftime("%Y-%m-%d")
    return f"projects/{primary_namespace()}/memory/builder-profile-noirdeck-{day}.md"


def run_heuristics(conn: sqlite3.Connection, claude_dir: Path) -> dict:
    """Compute the builder profile and stage it as a proposal. This is the whole
    local pass now: everything else requires a model to read the evidence."""
    records = hist.load_history(claude_dir)
    target = profile_target_path()
    created = 0
    # Never stage what approval would refuse. Create-only means an existing file
    # can't be replaced, so once today's profile is on disk a further proposal is
    # dead on arrival: and a Review list full of unappliable rows trains the
    # operator to ignore it.
    already_on_disk = (claude_dir / target).exists()
    pending = conn.execute("SELECT 1 FROM proposals WHERE target_path=? AND status='proposed'", (target,)).fetchone()
    if not already_on_disk and not pending:
        conn.execute(
            "INSERT INTO proposals (kind,title,body,target_path,status,created_at) VALUES (?,?,?,?,'proposed',?)",
            (
                "profile_doc",
                f"Builder profile & delivery methodology ({datetime.now(NZ).strftime('%Y-%m-%d')})",
                build_profile(records, claude_dir),
                target,
                utcnow(),
            ),
        )
        created = 1
    conn.commit()
    return {"proposals_created": created, "skill_candidates": 0}
